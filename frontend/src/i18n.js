let language = globalThis.localStorage?.getItem('journal.language') === 'ar' ? 'ar' : 'en';
export const getLanguage = () => language;
const listeners = new Set();
export function setLanguage(value) {
  language = value === 'ar' ? 'ar' : 'en';
  globalThis.localStorage?.setItem('journal.language', language);
  if (globalThis.document) {
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    document.title = language === 'ar' ? 'جورنال · إدارة المحتوى' : 'Journal · Blog Management';
  }
  listeners.forEach(listener => listener());
}
export function useLanguage() {
  return useSyncExternalStore(listener => { listeners.add(listener); return () => listeners.delete(listener); }, getLanguage);
}
export function t(key, values = {}) {
  const english = Object.keys(translations).find(source => translations[source] === key) || key;
  const text = language === 'ar' ? translations[english] || key : english;
  return String(text).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '{' + name + '}');
}
export const formatNumber = value => new Intl.NumberFormat(language === 'ar' ? 'ar-EG' : 'en-GB').format(value);
export const formatDate = (value, short = false) => value ? new Intl.DateTimeFormat(language === 'ar' ? 'ar-EG' : 'en-GB', short ? {dateStyle:'medium'} : {dateStyle:'medium',timeStyle:'short'}).format(new Date(value)) : '—';
setLanguage(language);
